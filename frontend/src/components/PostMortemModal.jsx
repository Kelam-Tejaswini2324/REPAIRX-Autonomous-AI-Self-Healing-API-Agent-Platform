import React, { useState, useEffect } from 'react';
import { X, FileText, Copy, Download, Sparkles, Check } from 'lucide-react';

export default function PostMortemModal({ incidentId, isOpen, onClose }) {
  const [postMortemData, setPostMortemData] = useState(null);
  const [copied, setCopied] = useState(false);

  useEffect(() => {
    if (isOpen && incidentId) {
      fetch(`/api/incidents/${incidentId}/postmortem`)
        .then(res => res.json())
        .then(data => {
          if (data.success) {
            setPostMortemData(data.data);
          }
        })
        .catch(console.error);
    }
  }, [isOpen, incidentId]);

  if (!isOpen || !postMortemData) return null;

  const handleCopy = () => {
    navigator.clipboard.writeText(postMortemData.markdown);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const element = document.createElement('a');
    const file = new Blob([postMortemData.markdown], { type: 'text/markdown' });
    element.href = URL.createObjectURL(file);
    element.download = `postmortem-${incidentId}.md`;
    document.body.appendChild(element);
    element.click();
    document.body.removeChild(element);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/80 backdrop-blur-md animate-fadeIn">
      <div className="glass-panel-glow rounded-3xl w-full max-w-4xl max-h-[90vh] overflow-hidden flex flex-col border border-purple-500/30 shadow-2xl">
        
        {/* Header */}
        <div className="flex items-center justify-between px-6 py-4 bg-slate-900/90 border-b border-slate-800">
          <div className="flex items-center gap-3">
            <div className="p-2 rounded-xl bg-purple-500/20 text-purple-400">
              <FileText className="w-5 h-5" />
            </div>
            <div>
              <div className="flex items-center gap-2">
                <h2 className="text-base font-black tracking-tight text-white uppercase">
                  Incident Post-Mortem Report ({incidentId})
                </h2>
                <span className="px-2 py-0.5 rounded-full text-[10px] font-bold bg-purple-900/60 text-purple-300 border border-purple-700/60">
                  Auto-Generated by AI
                </span>
              </div>
              <p className="text-xs text-slate-400">
                Formal RCA, impact assessment, patch diff, and long-term preventative action items.
              </p>
            </div>
          </div>

          <div className="flex items-center gap-2">
            <button
              onClick={handleCopy}
              className="flex items-center gap-1 px-3 py-1.5 rounded-xl bg-slate-800 hover:bg-slate-700 text-slate-200 text-xs font-semibold border border-slate-700 transition-all"
            >
              {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
              <span>{copied ? 'Copied!' : 'Copy Markdown'}</span>
            </button>
            <button
              onClick={handleDownload}
              className="flex items-center gap-1 px-3 py-1.5 rounded-xl bg-purple-600 hover:bg-purple-500 text-white text-xs font-semibold shadow-md transition-all"
            >
              <Download className="w-3.5 h-3.5" />
              <span>Download .md</span>
            </button>
            <button
              onClick={onClose}
              className="p-1.5 rounded-xl bg-slate-800 hover:bg-slate-700 text-slate-400 hover:text-white transition-all"
            >
              <X className="w-5 h-5" />
            </button>
          </div>
        </div>

        {/* Markdown Content Box */}
        <div className="p-6 overflow-y-auto font-mono text-xs bg-[#050811]/90 text-slate-200 space-y-4">
          <pre className="whitespace-pre-wrap leading-relaxed font-sans text-sm text-slate-300">
            {postMortemData.markdown}
          </pre>
        </div>

      </div>
    </div>
  );
}
